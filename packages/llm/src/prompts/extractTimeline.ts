/**
 * 本文から時系列情報を抽出するプロンプト。JSON 配列を返すよう指示する。
 */
export function extractTimeline(content: string): string {
  return `あなたは小説の分析者です。以下の小説本文から、時系列情報を抽出してください。

# 本文
${content}

# 指示
1. 本文中に登場する出来事を、時系列順に抽出してください。
2. 各出来事について、発生した時点（相対的な時間表現で可）と内容を記述してください。
3. 明確な時間が示されていない場合は、文脈から推測して相対的な順序を付けてください。
4. 出来事の重要度に関わらず、物語の流れを追うために必要なものを抽出してください。

# 出力形式
以下の JSON 配列形式で出力してください。JSON 以外のテキストは含めないでください。
[
  {
    "time": "時間の記述（例: 第1章の朝、3日後）",
    "event": "出来事の内容",
    "order": 1
  }
]`;
}
