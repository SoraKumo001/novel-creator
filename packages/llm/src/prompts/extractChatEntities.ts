/**
 * チャットテキストから登場人物、世界観設定、伏線、年表、プロットを抽出・構造化するプロンプト。
 */
export function extractChatEntities(text: string): string {
  return `あなたは小説の設定・ストーリー管理のアシスタントです。
以下のチャット会話テキストから、提案・議論されている「登場人物」「世界観・設定」「伏線」「時系列・年表」「プロット（章・節の展開）」を抽出し、構造化されたJSONオブジェクトとして出力してください。

# チャットテキスト
${text}

# 抽出ルール
1. **登場人物 (characters)**:
   - 名前が特定できるキャラクター、または明確な提案があるキャラクターを抽出してください。
   - name: キャラクターの名前（※「（既存キャラ）」「(新規)」などの説明注記は含めず、純粋な名前のみにしてください）
   - category: 役割や身分（例: 主人公, ヒロイン, 敵対者, 協力者, 王族, 未分類 など。※「（既存キャラ）」等の注記は含めず、純粋なカテゴリ名にしてください）
   - description: 外見、性格、背景、能力、動機、関係性などの詳細説明文
   - traits: 特徴や属性のキーワード文字列配列（例: ["銀髪", "冷静沈着", "炎魔法"]）
2. **世界観・設定 (settings)**:
   - 世界観、場所、魔法・技術、組織・国家、歴史・事件、アイテムなどの設定を抽出してください。
   - name: 設定の名称（※「（既存設定）」等の注記は含めないでください）
   - category: 設定の種別（例: 世界観, 地理・場所, 魔法・技術, 組織・国家, 歴史, アイテム など）
   - description: 設定の詳細説明
3. **伏線 (foreshadowings)**:
   - 設定された謎、仄めかし、伏線やその回収案を抽出してください。
   - title: 伏線のタイトル・概要（※注記は含めないでください）
   - description: 伏線の詳細（設置状況、真相、回収のアイデアなど）
   - status: "unresolved"（未回収）, "resolved"（回収済）, "abandoned"（破棄）のいずれか（通常は "unresolved"）
4. **時系列・年表 (timelines)**:
   - 作中または過去・未来の出来事やタイムラインを抽出してください。
   - event: 出来事の内容・要約
   - timestamp: 作中時期や日時・順序を表す文字列（例: "第1章直前", "魔王降臨の3年前", "物語開始から3日目" など。不明な場合は省略可）
5. **プロット・章あらすじ (plots)**:
   - 章や節の展開、あらすじ、ストーリー構成のアイデアを抽出してください。
   - title: 章または節のタイトル（例: "第1章：旅立ち", "プロローグ" など）
   - summary: その章・節のプロット、展開の要約
6. **注記の除外**: すべての項目で、「（既存キャラ）」「(既存)」「【新規】」「（既存設定）」などの文脈上のメタ注記は名前に含めず、純粋な名称のみを抽出してください。
7. チャットテキスト内に該当するものがない項目は空配列 [] にしてください。
8. 余計な前置きやMarkdownコードブロックは含めず、純粋なJSONオブジェクトのみを出力してください。

# 出力形式
{
  "characters": [
    {
      "name": "キャラクター名",
      "category": "役割/身分",
      "description": "詳細な説明",
      "traits": ["特徴1", "特徴2"]
    }
  ],
  "settings": [
    {
      "name": "設定名",
      "category": "カテゴリ",
      "description": "詳細な説明"
    }
  ],
  "foreshadowings": [
    {
      "title": "伏線タイトル",
      "description": "伏線の詳細内容",
      "status": "unresolved"
    }
  ],
  "timelines": [
    {
      "event": "出来事の内容",
      "timestamp": "作中時期または日時"
    }
  ],
  "plots": [
    {
      "title": "章/節タイトル",
      "summary": "プロット・あらすじ"
    }
  ]
}`;
}
