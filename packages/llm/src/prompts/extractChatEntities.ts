/**
 * チャットテキストから登場人物および設定を抽出・構造化するプロンプト。
 */
export function extractChatEntities(text: string): string {
  return `あなたは小説の設定・キャラクター管理のアシスタントです。
以下のチャット会話テキストから、提案されている「登場人物（キャラクター）」および「世界観・設定」を抽出し、構造化されたJSONオブジェクトとして出力してください。

# チャットテキスト
${text}

# 抽出ルール
1. **登場人物 (characters)**:
   - 名前が特定できるキャラクター、または明確な提案があるキャラクターを抽出してください。
   - category: 役割や身分（例: 主人公, ヒロイン, 敵対者, 協力者, 王族, 未分類 など）
   - name: キャラクターの名前
   - description: 外見、性格、背景、能力、動機、関係性などの詳細説明文
   - traits: 特徴や属性のキーワード文字列配列（例: ["銀髪", "冷静沈着", "炎魔法"]）
2. **世界観・設定 (settings)**:
   - 世界観、場所、魔法・技術、組織・国家、歴史・事件、アイテムなどの設定を抽出してください。
   - category: 設定の種別（例: 世界観, 地理・場所, 魔法・技術, 組織・国家, 歴史, アイテム など）
   - name: 設定の名称
   - description: 設定の詳細説明
3. チャットテキスト内に該当するものがない場合は空配列 [] にしてください。
4. 余計な前置きやMarkdownコードブロックは含めず、純粋なJSONオブジェクトのみを出力してください。

# 出力形式
{
  "characters": [
    {
      "name": "キャラクター名",
      "category": "役割/身分",
      "description": "詳細な説明",
      "traits": ["特徴1", "特徴2"]
    }
  ],
  "settings": [
    {
      "name": "設定名",
      "category": "カテゴリ",
      "description": "詳細な説明"
    }
  ]
}`;
}
